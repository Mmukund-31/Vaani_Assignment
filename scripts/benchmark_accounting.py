"""Independent accounting of the retrieval benchmark (does not reuse make_tables.py).

  python -m scripts.benchmark_accounting   -> results/summaries/benchmark_accounting.md

For each setting: run id; every attempt row; one FINAL response per unique question (the row in scenario
retrieval_<S>, never a retrieval_<S>_budget_wait row); whether that final response was a model answer or a model
refusal; its grade; denominators; and the attempts excluded from quality figures, split by cause.
"""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    questions = json.loads((ROOT / "evaluation" / "questions.json").read_text(encoding="utf-8"))
    qids = [q["id"] for q in questions]
    answerable = {q["id"] for q in questions if q["answerable"]}
    grades = json.loads((ROOT / "evaluation" / "grades.json").read_text(encoding="utf-8"))
    out = ["# Retrieval benchmark accounting (generated by scripts/benchmark_accounting.py)", "",
           "Final response = the single row of scenario `retrieval_<S>` for a question. Rows of scenario",
           "`retrieval_<S>_budget_wait` are attempts refused for the DAILY budget; the same question was asked again, so",
           "they are logged as requests but excluded from every quality figure. A question counts once.", ""]
    problems = []
    for setting in "ABCD":
        runs = sorted((ROOT / "results" / "runs").glob(f"groq-retrieval{setting}-*.csv"))
        if not runs:
            continue
        rows = []
        for f in runs:
            with f.open(encoding="utf-8") as fh:
                rows += list(csv.DictReader(fh))
        final = [r for r in rows if r["scenario"] == f"retrieval_{setting}"]
        waits = [r for r in rows if r["scenario"] == f"retrieval_{setting}_budget_wait"]
        per_q = Counter(r["question_id"] for r in final)
        dup = [q for q, n in per_q.items() if n > 1]
        missing = [q for q in qids if q not in per_q]
        if dup or missing:
            problems.append(f"{setting}: duplicate finals {dup}, missing {missing}")
        kinds = Counter()
        lines = []
        for r in sorted(final, key=lambda r: qids.index(r["question_id"])):
            g = grades.get(r["request_id"], {})
            grade = g.get("grade", "UNGRADED") if isinstance(g, dict) else g
            if r["status"] != "ok":
                kind = f"no response ({r['status']}/{r['error_type']})"
            else:
                kind = "model refusal" if r["decision"].startswith("refuse") else "model answer"
            kinds[kind] += 1
            if grade == "UNGRADED":
                problems.append(f"{setting}: {r['request_id']} has no grade")
            if r["question_id"] in answerable and grade == "refused_correctly":
                problems.append(f"{setting}: {r['request_id']} answerable but refused_correctly")
            if r["question_id"] not in answerable and grade == "correct":
                problems.append(f"{setting}: {r['request_id']} unanswerable but correct")
            attempts = 1 + sum(1 for w in waits if w["question_id"] == r["question_id"])
            lines.append(f"| {r['question_id']} | {r['request_id'].split(r['run_id'] + '-', 1)[-1]} | "
                         f"{attempts} | {kind} | {grade} |")
        gc = Counter((grades.get(r["request_id"]) or {}).get("grade") for r in final)
        n = len(final)
        n_ans = sum(1 for r in final if r["question_id"] in answerable)
        wait_causes = Counter("provider 429 (daily)" if w["error_type"].startswith("provider_429")
                              else f"local governor ({w['error_type']})" for w in waits)
        out += [f"## Setting {setting}", "",
                f"Run file(s): {', '.join(f.name for f in runs)}  ",
                f"Attempt rows: {len(rows)} = {n} final responses + {len(waits)} daily-budget attempts "
                f"({dict(wait_causes) or 'none'})  ",
                f"Questions: {n} of {len(qids)} (answerable {n_ans} of {len(answerable)}, unanswerable {n - n_ans} of "
                f"{len(qids) - len(answerable)})  ",
                f"Final responses: {dict(kinds)}  ",
                f"Grades: correct {gc['correct']}, wrong {gc['wrong']}, refused_correctly {gc['refused_correctly']}, "
                f"refused_wrongly {gc['refused_wrongly']}  ",
                f"Percent of {n}: correct {100 * gc['correct'] / n:.1f}, wrong {100 * gc['wrong'] / n:.1f}, "
                f"refused_correctly {100 * gc['refused_correctly'] / n:.1f}, "
                f"refused_wrongly {100 * gc['refused_wrongly'] / n:.1f}  ",
                f"Correct on answerable: {sum(1 for r in final if r['question_id'] in answerable and (grades.get(r['request_id']) or {}).get('grade') == 'correct')}/{n_ans}",
                "", "| Question | Final request id | Attempts | Final response | Grade |", "|---|---|---|---|---|",
                *lines, ""]
    out += ["## Problems found", "", *(problems or ["none"])]
    path = ROOT / "results" / "summaries" / "benchmark_accounting.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(x for x in out if not x.startswith("| ") and not x.startswith("|---")))


if __name__ == "__main__":
    main()
