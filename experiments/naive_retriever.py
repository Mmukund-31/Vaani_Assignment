"""Show how this library misleads a naive retriever (no model calls).

  python -m experiments.naive_retriever  -> results/summaries/naive_retriever.md

naive  = BM25, 600-token chunks, top-4, reference lists INCLUDED, one query, no paper routing
ours   = setting C (600/k4/re-rank, references excluded) + the planner's per-paper re-retrieval
"""
from __future__ import annotations

from pathlib import Path

from relay.pipeline import Pipeline
from relay.providers import MockProvider
from relay.retrieval import SETTINGS, RetrievalSetting, build_index

ROOT = Path(__file__).resolve().parent.parent
CASES = [
    ("1. Shared vocabulary across papers pulls the wrong paper's numbers",
     "What BLEU score does Moshi achieve on the WMT 2014 English-to-German translation benchmark?"),
    ("2. Same word, different meaning (compression)",
     "What compression ratio does the model achieve?"),
    ("3. Reference lists match on titles, not content",
     "What is layer normalization and who proposed it?"),
    ("4. Comparison question: one query covers one paper",
     "What input units does each of the three models consume: the Transformer for translation, Moshi, and H-Net?"),
]


def fmt(hits) -> list[str]:
    return [f"  {h.label} {h.chunk.paper:9s} p.{h.chunk.page_start:<3d} {h.chunk.section[:55]:55s} "
            f"| {h.chunk.text[:90].replace(chr(10), ' ')}" for h in hits]


def main():
    naive = build_index(RetrievalSetting("N", 600, 4, False, exclude_references=False))
    ours = Pipeline(MockProvider(), build_index(SETTINGS["C"]))
    lines = ["# Naive vs our retrieval (generated by experiments/naive_retriever.py)\n"]
    for title, q in CASES:
        lines += [f"## {title}", f"Q: {q}", "naive:"]
        hits = naive.search(q)
        for n, h in enumerate(hits, 1):
            h.label = f"P{n}"
        lines += fmt(hits)
        rec = Pipeline.intake(q, 20)
        lines += [f"ours (retrieval rounds={ours.retrieve_and_plan(rec) and rec.retrieval_rounds}):"]
        lines += fmt(ours.retrieve_and_plan(Pipeline.intake(q, 20)))
        lines.append("")
    out = ROOT / "results" / "summaries" / "naive_retriever.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
